/* psyq.c -- the PSY-Q libraries and the C runtime.
 *
 * Everything from 0x8003FA94 up. The split is measured, not assumed: no
 * function at or above that address calls any function below it, and it
 * is the lowest address for which that is true. A library object cannot
 * call into the game that links it, so that seam is where the linker
 * placed the SDK -- _start sits eight bytes above it.
 *
 * Why this matters more than tidiness: these 542 functions are not
 * bespoke. They were compiled from PSY-Q sources that exist, so matching
 * them is a question of finding the right library version and flags
 * rather than of guessing what the author wrote. m2c is the wrong tool
 * here and its poor hit rate on this region is not evidence about the
 * code.
 */
